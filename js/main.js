const $ = (s, c = document) => c.querySelector(s);
const $$ = (s, c = document) => [...c.querySelectorAll(s)];
const clamp = (v, a = 0, b = 1) => Math.min(b, Math.max(a, v));
const reduceMotion = matchMedia('(prefers-reduced-motion: reduce)').matches;

const nav = $('#nav');
const menuToggle = $('#menuToggle');
const navMenu = $('#navMenu');
const navLinks = $$('.nav-link');

const heroMedia = $('.hero-media');
const heroContent = $('.hero-content');
const scrollCue = $('.scroll-cue');
const collage = $('.collage');
const collageHeadline = $('.collage-headline');
const collageLines = $$('.cl');
const cards = $$('.c-card');
const parallaxImgs = $$('[data-parallax]');
const marquee = $('.marquee');
const marqueeTrack = $('.marquee-track');
const spySections = ['about', 'directors', 'research', 'events'].map(id => document.getElementById(id));

let vh = innerHeight;
let lastY = scrollY;
let ticking = false;
let sectionTops = [];

/* Sticky sections taller than the viewport stick at their bottom edge, so all content is seen before the next section covers them. */
function setCurtainTops() {
  $$('.curtain').forEach(el => {
    el.style.top = Math.min(0, vh - el.offsetHeight) + 'px';
  });
}

/* Sticky elements report their stuck position, so measure them in normal flow. */
function staticTop(el) {
  const { position, top: stickyTop } = el.style;
  el.style.position = 'relative';
  el.style.top = '0px';
  const top = el.getBoundingClientRect().top + scrollY;
  el.style.position = position;
  el.style.top = stickyTop;
  return top;
}

function measure() {
  vh = innerHeight;
  setCurtainTops();
  sectionTops = spySections.map(staticTop);
  update();
}

function update() {
  ticking = false;
  const y = scrollY;

  nav.classList.toggle('scrolled', y > 40);
  if (!navMenu.classList.contains('active')) {
    nav.classList.toggle('hidden', y > lastY && y > vh * 0.9);
  }
  lastY = y;

  let active = -1;
  sectionTops.forEach((top, i) => { if (y + vh * 0.4 >= top) active = i; });
  navLinks.forEach((link, i) => link.classList.toggle('active', i === active));

  if (reduceMotion) return;

  // Hero: image drifts down and zooms, copy rises and fades as the collage slides over
  const hp = clamp(y / vh);
  heroMedia.style.transform = `translate3d(0, ${hp * vh * 0.3}px, 0) scale(${1 + hp * 0.15})`;
  heroContent.style.transform = `translate3d(0, ${hp * -140}px, 0)`;
  heroContent.style.opacity = clamp(1 - hp * 1.3);
  scrollCue.style.opacity = clamp(1 - hp * 4);

  const cr = collage.getBoundingClientRect();
  if (cr.bottom > 0 && cr.top < vh) {
    const cp = clamp(-cr.top / (cr.height - vh));
    collageHeadline.style.opacity = clamp((cr.bottom - vh * 0.25) / (vh * 0.75));
    collageLines.forEach((line, i) => {
      const dir = i % 2 ? 1 : -1;
      line.style.transform = `translate3d(${dir * cp * 7}vw, 0, 0)`;
    });
    cards.forEach(card => {
      const center = cr.top + card.offsetTop + card.offsetHeight / 2;
      const ty = (center - vh / 2) * parseFloat(card.dataset.speed);
      card.style.transform = `translate3d(0, ${ty}px, 0)`;
    });
  }

  // Inner-image parallax, clamped to the image's overflow so no gaps appear
  parallaxImgs.forEach(img => {
    const box = img.parentElement;
    const r = box.getBoundingClientRect();
    if (r.bottom < -100 || r.top > vh + 100) return;
    const room = (img.offsetHeight - box.offsetHeight) / 2;
    const ty = clamp(-(r.top + r.height / 2 - vh / 2) * parseFloat(img.dataset.parallax), -room, room);
    img.style.transform = `translate3d(0, ${ty}px, 0)`;
  });

  const mr = marquee.getBoundingClientRect();
  if (mr.bottom > 0 && mr.top < vh) {
    marqueeTrack.style.transform = `translate3d(${(mr.top - vh) * 0.6}px, 0, 0)`;
  }
}

function requestUpdate() {
  if (!ticking) {
    ticking = true;
    requestAnimationFrame(update);
  }
}

function initReveal() {
  if (reduceMotion) return;
  const io = new IntersectionObserver(entries => {
    entries.forEach(entry => {
      if (entry.isIntersecting) {
        entry.target.classList.add('in');
        io.unobserve(entry.target);
      }
    });
  }, { threshold: 0.08, rootMargin: '0px 0px 72px 0px' });
  $$('.reveal, .media').forEach(el => io.observe(el));
}

function closeMenu() {
  menuToggle.classList.remove('active');
  navMenu.classList.remove('active');
  document.body.style.overflow = '';
}

function initMenu() {
  menuToggle.addEventListener('click', () => {
    const open = !navMenu.classList.contains('active');
    menuToggle.classList.toggle('active', open);
    navMenu.classList.toggle('active', open);
    document.body.style.overflow = open ? 'hidden' : '';
    nav.classList.remove('hidden');
  });
}

function initAnchors() {
  $$('a[href^="#"]').forEach(a => {
    a.addEventListener('click', e => {
      const id = a.getAttribute('href').slice(1);
      const target = id ? document.getElementById(id) : null;
      if (!target) return;
      e.preventDefault();
      closeMenu();
      scrollTo({ top: id === 'top' ? 0 : staticTop(target), behavior: reduceMotion ? 'auto' : 'smooth' });
    });
  });
}

function setLanguage(lang) {
  const t = translations[lang];
  if (!t) return;
  document.documentElement.lang = lang === 'zh' ? 'zh-CN' : lang;
  $$('[data-i18n]').forEach(el => {
    const value = t[el.dataset.i18n];
    if (value === undefined) return;
    if (el.tagName === 'TITLE') document.title = value;
    else el.textContent = value;
  });
  $$('.lang-btn').forEach(b => b.classList.toggle('active', b.dataset.lang === lang));
  localStorage.setItem('lang', lang);
  requestAnimationFrame(measure);
}

function initLanguage() {
  $$('.lang-btn').forEach(btn => btn.addEventListener('click', () => setLanguage(btn.dataset.lang)));
  const saved = localStorage.getItem('lang');
  if (saved && saved !== 'zh') setLanguage(saved);
}

document.addEventListener('DOMContentLoaded', () => {
  initMenu();
  initAnchors();
  initLanguage();
  initReveal();
  measure();
  addEventListener('scroll', requestUpdate, { passive: true });
  addEventListener('resize', measure);
  addEventListener('load', measure);
  new ResizeObserver(() => requestAnimationFrame(measure)).observe($('main'));
});
